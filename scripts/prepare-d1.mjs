import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { PrismaClient, Prisma } from "@prisma/client";

// Export only pristine fictional seed records, never the working presentation DB.
const name = `edge-export-${Date.now()}.db`;
const filename = path.resolve("prisma", name);
const env = {
  ...process.env,
  DATABASE_URL: `file:./${name}`,
  NODE_ENV: "development",
  DEMO_MODE: "true",
  ALLOW_HOSTED_DEMO_SEED: "false",
};
fs.closeSync(fs.openSync(filename, "wx"));
const client = new PrismaClient({ datasourceUrl: env.DATABASE_URL });
try {
  for (const args of [
    ["node_modules/prisma/build/index.js", "migrate", "deploy"],
    ["node_modules/tsx/dist/cli.mjs", "prisma/seed.ts"],
  ]) {
    const run = spawnSync(process.execPath, args, { env, stdio: "inherit" });
    if (run.status !== 0) throw new Error("Pristine seed export failed.");
  }
  const models = Prisma.dmmf.datamodel.models;
  const data = [];
  for (const model of models) {
    const records =
      await client[
        model.name[0].toLowerCase() + model.name.slice(1)
      ].findMany();
    for (const record of records)
      if (record.email === "admin@sunka.demo") record.passwordHash = null;
    if (records.length) data.push([model.name, records]);
  }
  fs.mkdirSync("src/edge", { recursive: true });
  fs.writeFileSync(
    "src/edge/seed-data.json",
    JSON.stringify(data, null, 2) + "\n",
  );
  let source =
    '// Schema mirrors prisma/schema.prisma; generated by scripts/prepare-d1.mjs.\nimport { sqliteTable, text, integer, uniqueIndex } from "drizzle-orm/sqlite-core";\nimport { sql } from "drizzle-orm";\n';
  for (const model of models) {
    source += `\nexport const ${model.name} = sqliteTable(${JSON.stringify(model.name)}, {\n`;
    for (const field of model.fields.filter((f) => f.kind === "scalar")) {
      let column = ["Int", "Boolean"].includes(field.type)
        ? `integer(${JSON.stringify(field.name)}${field.type === "Boolean" ? ', { mode: "boolean" }' : ""})`
        : `text(${JSON.stringify(field.name)})`;
      if (field.isId) column += ".primaryKey()";
      else if (field.isRequired) column += ".notNull()";
      if (field.isUnique) column += ".unique()";
      if (
        field.hasDefaultValue &&
        (typeof field.default !== "object" || field.default === null)
      )
        column += `.default(${JSON.stringify(field.default)})`;
      if (field.type === "DateTime" && field.default?.name === "now")
        column += ".default(sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`)";
      const relation = model.fields.find((f) =>
        f.relationFromFields?.includes(field.name),
      );
      if (relation)
        column += `.references(() => ${relation.type}.${relation.relationToFields[relation.relationFromFields.indexOf(field.name)]}${relation.relationOnDelete === "Cascade" ? ', { onDelete: "cascade" }' : ""})`;
      source += `  ${field.name}: ${column},\n`;
    }
    source += "}";
    if (model.uniqueFields.length)
      source += `, (table) => [${model.uniqueFields.map((fields) => `uniqueIndex(${JSON.stringify(model.name + "_" + fields.join("_") + "_key")}).on(${fields.map((f) => "table." + f).join(",")})`).join(",")}]`;
    source += ");\n";
  }
  source +=
    '\nexport const SeedState = sqliteTable("SeedState", { id: text("id").primaryKey(), appliedAt: text("appliedAt").notNull() });\n';
  fs.mkdirSync("db", { recursive: true });
  fs.writeFileSync("db/schema.ts", source);
  console.log(
    "Exported pristine seed and D1 schema; no working customer records or administrator hash included.",
  );
} finally {
  await client.$disconnect();
  if (fs.existsSync(filename)) fs.unlinkSync(filename);
}
